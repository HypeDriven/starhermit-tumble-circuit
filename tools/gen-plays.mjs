// Writes the render-check play scripts (tests/native/*.play) from rhythms
// tools/plan.mjs finds with the real rules: each won round is "hold W, tap
// Jump then Dive" at the planned F / A / B. Run after a rules or content
// change: node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { search } from './plan.mjs';

const plan = (spec) => { const p = search(spec); if (!p) throw new Error('no winning rhythm for ' + spec); return p; };
/** One round by keys from GO to its results. */
function round(p, until = 'Score breakdown') {
  return [
    'until 400 =GO!', `frames ${p.F}`, 'hold KeyW', `repeat 9000 until ${until}`,
    'key Space 1', `frames ${p.A}`, 'key ShiftLeft 1', `frames ${p.B}`, 'end', 'release KeyW', 'frames 30',
  ];
}
const head = (title, viewport) => [...title.map((l) => '# ' + l), `# viewport ${viewport}`, 'until 600 Tumble', 'frames 30'];
const tap = (how, text) => [`${how} ${text}`];

// The five lessons on a desktop window, by keys; Next lesson between them.
{
  const lines = head(['The five Learn lessons won by keys on a desktop window (W held, Jump then Dive on',
    'the rhythm tools/plan.mjs found for each); each results screen, then Next lesson;',
    'the last one unlocks Graduate. Generated by tools/gen-plays.mjs.'], '1280x800@1');
  lines.push('click Play', 'until 300 Choose a mode', 'frames 10', 'click Learn', 'until 300 One rule at a time', 'frames 10', 'save tc-learn-list', 'click 1. Move Out');
  for (let i = 0; i < 5; i++) {
    lines.push(...round(plan('lesson:' + i)), 'expect complete!');
    if (i === 0) lines.push('save tc-learn-results');
    if (i < 4) lines.push('click Next lesson');
    else lines.push('expect Graduate', 'save tc-learn-done');
  }
  writeFileSync('tests/native/learn-keys.play', lines.join('\n') + '\n');
}
// Journey stages 1 and 2 on a phone (390 x 844 at DPR 3): menus by finger, the race by keys.
{
  const lines = head(['Journey stages 1 and 2 on a phone (390 x 844 at DPR 3): the menus by finger, the',
    'races by keys on tools/plan.mjs rhythms; both pass; the HUD wraps within the width.',
    'Generated by tools/gen-plays.mjs.'], '390x844@3');
  lines.push(...tap('touch', 'Play'), 'until 300 Choose a mode', 'frames 10', 'save tc-phone-modes', ...tap('touch', 'Journey'),
    'until 300 Unlocked through', 'frames 10', 'save tc-phone-journey', ...tap('touch', '1. Warm-Up Walk'));
  lines.push(...round(plan('stage:1')), 'expect passed!', 'save tc-phone-results', ...tap('touch', 'Stage 2'));
  lines.push(...round(plan('stage:2')), 'expect passed!');
  writeFileSync('tests/native/journey-phone.play', lines.join('\n') + '\n');
}
// The Quick Show on a desktop window: each round on a rhythm that qualifies (the
// show's own rosters, replayed with js/rules/show.js), Continue show, the final, the show table.
{
  const { SHOWS, courseById } = await import('../js/content/stages.js');
  const { buildRoster, PALETTE } = await import('../js/session/round.js');
  const S = await import('../js/rules/show.js');
  const { play } = await import('./plan.mjs');
  const { LocalRound } = await import('../js/session/round.js');
  const { DT } = await import('../js/rules/sim.js');
  const def = SHOWS[0];
  const show = S.createShow(def, buildRoster('You', PALETTE[0], def.players - 1, 7));
  const lines = head(['The Quick Show on a desktop window: three rounds by keys on rhythms tools/plan.mjs',
    'checks against the show\'s own rosters, Continue show after each, then the show table.',
    'Generated by tools/gen-plays.mjs.'], '1280x800@1');
  lines.push('click Play', 'until 300 Choose a mode', 'frames 10', 'click Show', 'until 300 Survive each cut', 'frames 10', 'click Quick Show');
  while (!show.terminal && show.aliveIds.includes('you')) {
    const rd = S.currentRound(show);
    const c = courseById(rd.courseId);
    const roster = show.roster.filter((r) => show.aliveIds.includes(r.id));
    const opts = { quota: Math.min(rd.quota, roster.length), botSkill: def.botSkill };
    let pick = null;
    for (let P = 6; P <= 30 && !pick; P++) for (let A = 0; A <= P - 5 && !pick; A++) {
      const res = play(c, opts, { F: 2, A, B: P - 5 - A, roster });
      if (res.qualified || S.isFinalRound(show)) pick = { F: 2, A, B: P - 5 - A };
    }
    // replay the picked round to advance the show model
    const r = new LocalRound(c, roster, opts);
    const H = 5, J0 = 7, Pp = pick.A + pick.B + 5, D = pick.A + 2;
    while (r.phase !== 'done') { const a = r.phase === 'active'; const T = r.state.tick + 1;
      r.setInput({ mx: 0, mz: a && T >= H ? 1 : 0, jump: a && T >= J0 && (T - J0) % Pp === 0, dive: a && T >= J0 + D && (T - J0 - D) % Pp === 0 }); r.update(DT); }
    lines.push(...round(pick), 'click Continue show');
    S.applyRoundResult(show, r.result);
  }
  lines.push('until 600 Points', 'frames 10', 'save tc-show-over');
  writeFileSync('tests/native/show-desktop.play', lines.join('\n') + '\n');
}
